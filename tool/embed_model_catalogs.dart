import 'dart:convert';
import 'dart:io';

/// Rebuild checked-in constants. Runtime and AOT builds never read these files.
Future<void> main() async {
  for (final lab in ['gpt', 'deepseek']) {
    final input = File('packages/$lab/catalog/models.json');
    final source = await input.readAsString();
    final decoded = jsonDecode(source);
    if (decoded is! Map || decoded['models'] is! List) {
      throw FormatException('Invalid $lab model catalog');
    }
    if (source.contains("'''")) {
      throw FormatException('Catalog contains the Dart raw-string delimiter');
    }
    await File('packages/$lab/lib/src/catalog_data.dart').writeAsString(
      "// Generated by tool/embed_model_catalogs.dart. Do not edit.\n"
      "// dart format off\n"
      "const modelCatalogJson = r'''$source''';\n",
    );
  }
}
