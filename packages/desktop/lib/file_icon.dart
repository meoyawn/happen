/// OpenCode's file and folder icons, including compound suffixes and config names.
class FileIcon extends StatelessWidget {
  const FileIcon(this.path, {super.key, this.size = 16, this.expanded = false});
  final String path;
  final double size;
  final bool expanded;

  @override
  Widget build(BuildContext context) => SvgPicture.asset(
    'assets/file-types/${fileIconName(path, expanded: expanded)}.svg',
    width: size, height: size,
    placeholderBuilder: (_) => SizedBox.square(dimension: size),
  );
}

String fileIconName(String path, {bool expanded = false}) {
  final parts = path.replaceAll(r'\', '/').split('/').where((part) => part.isNotEmpty);
  final name = parts.isEmpty ? '' : parts.last.toLowerCase();
  if (path.endsWith('/') || path.endsWith(r'\')) {
    var icon = _folderNames[name];
    icon ??= _folderNames['.$name'] ?? _folderNames['_$name'] ?? _folderNames['__${name}__'];
    icon ??= 'folder';
    return expanded ? '$icon-open' : icon;
  }
  final named = _fileNames[name];
  if (named != null) return named;
  var suffix = name;
  while (true) {
    final icon = _fileExtensions[suffix];
    if (icon != null) return icon;
    final dot = suffix.indexOf('.');
    if (dot < 0) return 'document';
    suffix = suffix.substring(dot + 1);
  }
}

